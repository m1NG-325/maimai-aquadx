"""Build archive thumbnails from user-selected game resources. Development only: UnityPy/Pillow."""
import argparse,json,re,hashlib
from pathlib import Path
import xml.etree.ElementTree as ET
import UnityPy
from PIL import Image

def build(root,out,covers):
 roots=[root/'StreamingAssets'/'A000',*sorted((p for p in root.iterdir() if re.fullmatch(r'A\d+',p.name)),key=lambda p:int(p.name[1:]))]
 bundles={};xml={}
 kinds={'Chara.xml':'chara','Partner.xml':'partner','Map.xml':'map','Course.xml':'course','LoginBonus.xml':'bonus'}
 for base in roots:
  for p in (base/'AssetBundleImages').rglob('*.ab'):bundles[p.relative_to(base/'AssetBundleImages').as_posix()]=p
  for p in base.rglob('*.xml'):
   if p.name in kinds:
    tree=ET.parse(p).getroot();identifier=tree.findtext('name/id')
    if identifier and identifier.isdigit():xml[kinds[p.name],identifier]=tree
 out.mkdir(parents=True,exist_ok=True);entries={};fail=[];prior={}
 if (out/'manifest.json').exists():
  prior=json.loads((out/'manifest.json').read_text(encoding='utf-8'));entries=dict(prior.get('entries',{}))
 def save(kind,identifier,img,source):
  img.thumbnail((160,100));name=f'{kind}-{identifier}.png';img.save(out/name)
  entries[f'{kind}:{identifier}']={'file':name,'source':source}
 def extract(key):
  p=bundles.get(key)
  if not p:return None
  env=UnityPy.load(str(p));objects=[o for o in env.objects if o.type.name=='Sprite'] or [o for o in env.objects if o.type.name=='Texture2D']
  if not objects:return None
  return objects[0].read().image.convert('RGBA')
 for (kind,identifier),tree in xml.items():
  try:
   key=None
   if kind in ('chara','partner'):key=f'{kind}/ui_{kind}_{int(identifier):06d}.ab'
   if key:
    img=extract(key)
    if img is not None:save(kind,identifier,img,key)
   elif kind=='course':
    ids=[n.text for n in tree.findall('courseMusicData/CourseMusicData/musicId/id')]
    pictures=[]
    for mid in ids:
     paths=[covers/f'{int(mid):05d}.png',covers/f'{int(mid)}.png']
     p=next((p for p in paths if p.exists()),None)
     if p:
      with Image.open(p) as im:pictures.append(im.convert('RGBA').resize((64,64)))
    if pictures:
     img=Image.new('RGBA',(64*len(pictures),64))
     for i,im in enumerate(pictures):img.paste(im,(i*64,0))
     save(kind,identifier,img,'Course.xml courseMusicData: '+','.join(ids))
  except Exception as exc:fail.append([kind,identifier,type(exc).__name__])
 for (kind,identifier),tree in xml.items():
  if kind!='bonus':continue
  target={'Partner':('partner','PartnerId/id'),'Character':('chara','CharacterId/id')}.get(tree.findtext('BonusType'))
  if target:
   ref=entries.get(f'{target[0]}:{tree.findtext(target[1])}')
   if ref:entries[f'bonus:{identifier}']=dict(ref,source='LoginBonus.xml '+target[1])
 manifest={**prior,'source':'Local game XML IDs and AssetBundle sprites; map artwork is generated by build_map_details.py from the last NamePlate reward; course thumbnails show referenced songs. Original game artwork belongs to its respective owners.','extractor':'UnityPy 1.25.4; Pillow','entries':entries,'unavailable':fail}
 (out/'manifest.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
 print({kind:sum(k.startswith(kind+':') for k in entries) for kind in kinds.values()},'errors',len(fail))
if __name__=='__main__':
 p=argparse.ArgumentParser();p.add_argument('game',type=Path);p.add_argument('output',type=Path);p.add_argument('covers',type=Path);a=p.parse_args();build(a.game,a.output,a.covers)
